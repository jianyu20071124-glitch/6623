/**
  ******************************************************************************
  * @file    step_seq.h
  * @brief   位置阶跃序列发生器（T-06 / T-07 批量测试用）
  * @note    每 1 秒切换一次目标角度，序列：
  *            0 → +30 → 0 → −30 → 0 → +90 → 0 → −90 → 0 → +180 → 0 → −180 → 0 …
  *          每步都回到中心再走下一档，保证每次阶跃幅度 ≤180°，
  *          避免 +180 → −180 这种 360° 跳变（误差归一化会当成 0 步）。
  ******************************************************************************
  */
#ifndef __STEP_SEQ_H
#define __STEP_SEQ_H

#include "main.h"

/* ================= 参数 ================= */
#define SEQ_STEP_MS   1000u      /* 每一步保持时间（ms） */

/* ================= 接口 ================= */
void     Seq_Init(void);                 /* 上电初始化 */
void     Seq_Start(float center_deg);    /* 以 center_deg 为中心开始序列 */
void     Seq_Stop(void);                 /* 停止序列（保持当前目标） */
uint8_t  Seq_Update(void);               /* 主循环调用；有新目标时返回 1 */
float    Seq_Get_Target(void);           /* 当前目标角度（绝对） */
uint8_t  Seq_Is_Running(void);           /* 1 = 序列进行中 */
uint16_t Seq_Get_Index(void);            /* 当前是第几步（调试用） */

#endif /* __STEP_SEQ_H */
