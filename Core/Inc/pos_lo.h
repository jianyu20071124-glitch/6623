/**
  ******************************************************************************
  * @file    pos_lo.h
  * @brief   位置单环控制器（F-06）—— 位置误差直接输出电流（无内环）
  * @note    与 cascade.c 的区别：
  *            pos_lo.c  = 位置 → 电流（一级）
  *            cascade.c = 位置 → 转速 → 电流（两级）
  *
  *          本版特点：靠"死区补偿"消除稳态误差，而不是靠积分硬拉。
  *          实测摩擦死区 26 count，补偿量取 34（约 1.3 倍），
  *          保证误差还在时电机一定动得起来。
  ******************************************************************************
  */
#ifndef __POS_LO_H
#define __POS_LO_H

#include "main.h"
#include "pid.h"

/* ================= 可调参数 =================
 * 注意：单环的 Kp 单位是 count/°，比串级位置环的 rpm/° 大一个数量级，
 *       因为它要自己承担全部电流调节，没有内环帮忙放大。
 *
 * 提速思路：Kp 调大 → 大误差时输出直接顶到限幅（全力冲）；
 *           限幅决定"最大能有多快"。
 */
#define PL_KP          60.0f     /* count/°  —— 大误差时顶满限幅，全力冲 */
#define PL_KI          20.0f     /* count/(°·s) —— 只需消最后一点点残差 */
#define PL_KD           0.0f     /* count/(°/s) */
#define PL_OUT_MAX   5000.0f     /* 电流限幅（count）—— 4900 留一点余量 */
#define PL_INT_MAX    500.0f     /* 积分限幅（count）*/

/* ================= 死区补偿 =================
 * PL_DZ_COMP：补偿电流，必须大于摩擦死区（实测 26 count）才能推动电机
 * PL_DZ_ERR ：只有误差大于这个值才补偿，避免在目标点附近来回推（极限环） */
#define PL_DZ_COMP     34.0f     /* count，约 26 × 1.3 */
#define PL_DZ_ERR       0.15f    /* °，小于它不补偿 */

/* ================= 积分分离 =================
 * 大误差阶段不积分（防积分饱和导致冲过头），
 * 误差进入 PL_I_ZONE 以内才让积分介入消除残差 */
#define PL_I_ZONE       5.0f     /* ° */

/* ================= 接口 ================= */
void  PL_Init(void);                       /* 初始化 */
float PL_Calc(float target_deg, float meas_deg);  /* 算一次电流，返回 count */
PID_T *PL_Get_PID(void);                   /* 取 PID 实例（调参用）*/

#endif /* __POS_LO_H */
