uint8_t CAN_Send(uint32_t id, uint8_t *buf)
{
  CAN_TxHeaderTypeDef tx;
  uint32_t mb;

  if (HAL_CAN_GetTxMailboxesFreeLevel(&hcan) == 0u) return 1u;

  tx.StdId = id;
  tx.ExtId = 0;
  tx.IDE   = CAN_ID_STD;
  tx.RTR   = CAN_RTR_DATA;
  tx.DLC   = 8;
  tx.TransmitGlobalTime = DISABLE;

  return (HAL_CAN_AddTxMessage(&hcan, &tx, buf, &mb) == HAL_OK) ? 0u : 1u;
}

